/**
 * Builds scripts/the-first-relics.js from the parts in src/.
 *
 *   node tools/build.cjs          write the bundle
 *   node tools/build.cjs --check  exit 1 if the bundle is out of date
 *
 * The parts are joined in file-name order into one ES module, so every part
 * shares one scope exactly as before the split: no imports or exports needed.
 * Edit src/, never the bundle.
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const srcDir = path.join(root, "src");
const out = path.join(root, "scripts", "the-first-relics.js");

const files = fs.readdirSync(srcDir).filter(f => /^\d\d-.+\.js$/.test(f)).sort();
let bundle = "// Generated by tools/build.cjs from src/*.js. Edit src/, then run: node tools/build.cjs\n";
for (const file of files) {
  const text = fs.readFileSync(path.join(srcDir, file), "utf8");
  if (text.includes("\r")) throw new Error(`${file}: CRLF line endings`);
  // A stray control character (e.g. a backspace from a mis-escaped "\b") silently breaks regexes.
  const control = text.search(/[\x00-\x08\x0B\x0C\x0E-\x1F]/);
  if (control >= 0) throw new Error(`${file}: control character at line ${text.slice(0, control).split("\n").length}`);
  bundle += `// ---- src/${file} ----\n${text.endsWith("\n") ? text : `${text}\n`}`;
}

const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
if (process.argv.includes("--check")) {
  if (current !== bundle) {
    console.error("scripts/the-first-relics.js is out of date: run node tools/build.cjs");
    process.exit(1);
  }
  console.log(`Bundle up to date (${files.length} parts).`);
} else {
  fs.writeFileSync(out, bundle);
  console.log(`Built scripts/the-first-relics.js from ${files.length} parts (${bundle.split("\n").length - 1} lines).`);
}
